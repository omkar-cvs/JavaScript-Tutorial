//Primitive Data Type
//String
console.log("---------[DataType: string]--------------");
let name = "Omkar Singh";
console.log(name);
console.log(typeof name);

console.log("---------[DataType: number]--------------");
let age = 20;
console.log(age);
console.log(typeof age);

console.log("---------[DataType: boolean]--------------");
let isStudent = true;
console.log(isStudent);
console.log(typeof isStudent);

console.log("---------[DataType: null]->[object]--------------");
let emptyValue = null;
console.log(emptyValue);
console.log(typeof emptyValue);

console.log("---------[DataType: undefined]--------------");
let abc;
console.log(abc);
console.log(typeof abc);

console.log("---------[DataType: bigint]--------------");
let bigIntValue = 123456789n;
console.log(bigIntValue);
console.log(typeof bigIntValue);

console.log("---------[DataType: symbol]--------------");
let symbolValue = Symbol("unique");
console.log(symbolValue);
console.log(typeof symbolValue);
